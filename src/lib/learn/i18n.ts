/** Part-of-speech labels are Persian in the data; translate them for the English UI. */
export function posLabel(pos: string, lang: Lang): string {
  if (lang === "fa" || !pos) return pos;
  return pos
    .split(/\s*([،,/])\s*/)
    .map((part) => (part === "،" || part === "," ? ", " : part === "/" ? " / " : (POS_EN[part] ?? part)))
    .join("");
}
